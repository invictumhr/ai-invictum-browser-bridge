#!/usr/bin/env bash
# Registers the development Native Messaging host on macOS and Linux.
# Windows uses scripts/register-native-host-dev.ps1 (compiled launcher + registry).
set -euo pipefail

# shellcheck source=lib/posix-common.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/posix-common.sh"

usage() {
  cat <<'EOF'
Usage: scripts/register-native-host-dev.sh [options]

  --extension-id ID     Extension ID shown on chrome://extensions.
  --extension-dir DIR   Unpacked extension directory used to derive the ID when
                        --extension-id is not given (default: apps/extension/dist).
  --desktop-url URL     Desktop Authority native socket
                        (default: ws://127.0.0.1:47821/native).
  --browser NAME        chrome (default), chrome-beta, chromium, edge or brave.

Without --extension-id the ID is derived exactly as Chrome does for an unpacked
extension without a "key", so registration can happen before the extension is
loaded. Load it afterwards from the same directory.
EOF
}

repo_root="$(ibb_repo_root)"
extension_id=""
extension_dir="$repo_root/apps/extension/dist"
desktop_url="ws://127.0.0.1:47821/native"
browser="chrome"

while [ $# -gt 0 ]; do
  case "$1" in
    --extension-id) extension_id="${2:-}"; shift 2 ;;
    --extension-dir) extension_dir="${2:-}"; shift 2 ;;
    --desktop-url) desktop_url="${2:-}"; shift 2 ;;
    --browser) browser="${2:-}"; shift 2 ;;
    -h | --help) usage; exit 0 ;;
    *) usage >&2; ibb_fail "unknown argument: $1" ;;
  esac
done

node_path="$(command -v node || true)"
[ -n "$node_path" ] || ibb_fail "node was not found on PATH"
host_entry="$repo_root/apps/native-host/dist/index.js"
[ -f "$host_entry" ] || ibb_fail "native host build not found at $host_entry; run pnpm build first"

if ! [[ "$desktop_url" =~ ^ws://127\.0\.0\.1:[0-9]{1,5}/[A-Za-z0-9/_-]+$ ]]; then
  ibb_fail "--desktop-url must be ws://127.0.0.1:<port>/<path>"
fi

if [ -z "$extension_id" ]; then
  [ -f "$extension_dir/manifest.json" ] || ibb_fail "extension build not found at $extension_dir; run pnpm build first"
  if grep -q '"key"[[:space:]]*:' "$extension_dir/manifest.json"; then
    ibb_fail "the extension manifest has a \"key\", so its ID does not depend on the path; pass --extension-id"
  fi
  extension_dir="$(cd "$extension_dir" && pwd -P)"
  extension_id="$(ibb_unpacked_extension_id "$node_path" "$extension_dir")"
fi
if ! [[ "$extension_id" =~ ^[a-p]{32}$ ]]; then
  ibb_fail "extension ID must be 32 characters a-p"
fi

manifest_dir="$(ibb_native_host_dir "$browser")"
manifest_path="$manifest_dir/$IBB_HOST_NAME.json"
development_dir="${IBB_DEVELOPMENT_DIR:-$repo_root/.development}"
launcher_path="$development_dir/invictum-native-host.sh"
mkdir -p "$development_dir" "$manifest_dir"

# Chrome starts the host with a minimal environment, so the launcher pins absolute
# paths. Chrome appends the caller origin as an argument; it is forwarded.
launcher_tmp="$(mktemp "$development_dir/.invictum-native-host.XXXXXX")"
{
  printf '#!/bin/sh\n'
  printf '# Generated by scripts/register-native-host-dev.sh; regenerate instead of editing.\n'
  printf 'exec %s %s %s "$@"\n' \
    "$(ibb_shell_quote "$node_path")" \
    "$(ibb_shell_quote "$host_entry")" \
    "$(ibb_shell_quote "--desktop-url=$desktop_url")"
} >"$launcher_tmp"
chmod 755 "$launcher_tmp"
mv -f "$launcher_tmp" "$launcher_path"

"$node_path" -e '
  const [manifestPath, name, launcherPath, extensionId] = process.argv.slice(1);
  const manifest = {
    name,
    description: "Invictum Browser Bridge Native Messaging Host (development)",
    path: launcherPath,
    type: "stdio",
    allowed_origins: [`chrome-extension://${extensionId}/`],
  };
  require("node:fs").writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
' "$manifest_path" "$IBB_HOST_NAME" "$launcher_path" "$extension_id"
cp "$manifest_path" "$development_dir/$IBB_HOST_NAME.json"

echo "Registered $IBB_HOST_NAME for extension $extension_id ($browser)"
echo "Manifest: $manifest_path"
echo "Launcher: $launcher_path"
echo "Load the unpacked extension from: $extension_dir"
